/**
 * Generated module index builder.
 *
 * Flo rewrites `src/modules/generated/index.ts` after every successful
 * generation. The file statically imports each generated module's view map
 * (registering it at import time) and exposes lazy controller loaders, so the
 * orchestrator only needs a one-time wiring change:
 *
 *   // src/engine/registrations.ts
 *   import { generatedControllerLoaders } from "@/modules/generated";
 *   export const controllerLoaders = {
 *     ...baseLoaders,
 *     ...generatedControllerLoaders,
 *   };
 *
 *   // src/modules/views.ts
 *   import "@/modules/generated";
 *
 * The generated index is intentionally a static module: Next.js can only
 * bundle imports it can see at build time, so a newly generated module is
 * available after the dev server recompiles (or the app is restarted).
 */

import type { GeneratedModuleManifest } from "../FloTypes";
import { js } from "./helpers";

function validIdentifier(value: string): boolean {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value);
}

/** Build the full text of src/modules/generated/index.ts. */
export function buildGeneratedIndex(modules: GeneratedModuleManifest[]): string {
  const sorted = [...modules].sort((a, b) =>
    a.module_name.localeCompare(b.module_name)
  );

  const lines: string[] = [];
  lines.push("/*");
  lines.push(" * AUTO-GENERATED by Flo — do not edit by hand.");
  lines.push(" *");
  lines.push(" * This file is rebuilt whenever a module is generated. See");
  lines.push(" * ./README.md for the one-time orchestrator wiring.");
  lines.push(" */");
  lines.push("");
  lines.push('import type { ControllerCtor } from "@/engine/controller";');
  lines.push('import { registerViews } from "@/engine/views-registry";');

  for (const manifest of sorted) {
    if (
      !validIdentifier(manifest.class_name) ||
      !/^[a-z0-9_]+$/.test(manifest.module_name)
    ) {
      continue;
    }
    lines.push(
      `import { views as ${manifest.class_name}Views } from ${js(
        `./${manifest.module_name}/views`
      )};`
    );
  }

  lines.push("");
  for (const manifest of sorted) {
    if (
      !validIdentifier(manifest.class_name) ||
      !/^[a-z0-9_]+$/.test(manifest.module_name)
    ) {
      continue;
    }
    lines.push(`registerViews(${manifest.class_name}Views);`);
  }
  if (sorted.length === 0) {
    lines.push("// No generated modules yet.");
  }

  lines.push("");
  lines.push("/** Metadata for every generated module. */");
  lines.push(
    "export const generatedModules: Record<string, GeneratedModuleManifest> = {"
  );
  for (const manifest of sorted) {
    lines.push(`  ${js(manifest.module_name)}: ${JSON.stringify(manifest, null, 2)
      .split("\n")
      .map((line, index) => (index === 0 ? line : "  " + line))
      .join("\n")},`);
  }
  lines.push("};");
  lines.push("");
  lines.push("/** Lazy controller loaders, spread into the orchestrator registry. */");
  lines.push(
    "export const generatedControllerLoaders: Record<string, () => Promise<{ default: ControllerCtor }>> = {"
  );
  for (const manifest of sorted) {
    if (
      !validIdentifier(manifest.class_name) ||
      !/^[a-z0-9_]+$/.test(manifest.module_name)
    ) {
      continue;
    }
    lines.push(
      `  ${js(manifest.module_name)}: () => import(${js(
        `./${manifest.module_name}/${manifest.class_name}`
      )}),`
    );
  }
  lines.push("};");
  lines.push("");
  lines.push("/** Shape of the manifest entries exposed above. */");
  lines.push("export interface GeneratedModuleManifest {");
  lines.push("  module_name: string;");
  lines.push("  class_name: string;");
  lines.push("  record_name_singular: string;");
  lines.push("  record_name_plural: string;");
  lines.push("  nav_label: string;");
  lines.push("  url_column: string;");
  lines.push("  order_by: string;");
  lines.push("  has_searchable: boolean;");
  lines.push("  view_files: string[];");
  lines.push('  generated_by: "flo" | "site_builder";');
  lines.push("  generated_at: string;");
  lines.push("}");
  lines.push("");

  return lines.join("\n");
}
