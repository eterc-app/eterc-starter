/**
 * SQLite table definition template.
 */
import type { PostedProperty, TemplateContext } from "../FloTypes";

const NUMERIC_SQL_TYPES = ["INT", "DECIMAL(10,2)", "TINYINT(1)"];

function extractMaxLength(rules: string[]): number {
  for (const rule of rules) {
    if (rule.startsWith("max length[")) {
      const start = rule.indexOf("[");
      const end = rule.indexOf("]", start + 1);
      if (start !== -1 && end !== -1) {
        const value = rule.slice(start + 1, end);
        if (value !== "" && /^\d+$/.test(value)) {
          return Number(value);
        }
      }
    }
  }
  return 255;
}

function mapPropertyTypeToSql(property: PostedProperty): string {
  switch (property.property_type) {
    case "varchar":
      return `VARCHAR(${extractMaxLength(property.validation_rules)})`;
    case "textarea":
      return "TEXT";
    case "int":
      return "INT";
    case "decimal":
      return "DECIMAL(10,2)";
    case "boolean":
      return "TINYINT(1)";
    case "email":
      return "VARCHAR(255)";
    case "date":
      return "DATE";
    case "time":
      return "TIME";
    case "date and time":
      return "DATETIME";
    default:
      return "VARCHAR(255)";
  }
}

/** Build the SQLite CREATE TABLE statement. */
export function buildTableSql(data: TemplateContext): string {
  const columns: string[] = [];
  columns.push("    `id` INTEGER PRIMARY KEY AUTOINCREMENT");

  for (const property of data.posted_properties) {
    const field_name = property.form_field_name;
    const col_type = mapPropertyTypeToSql(property);
    const is_required = property.validation_rules.includes("required");
    const null_clause = is_required
      ? " NOT NULL"
      : NUMERIC_SQL_TYPES.includes(col_type)
        ? " DEFAULT 0"
        : " DEFAULT NULL";

    columns.push(`    \`${field_name}\` ${col_type}${null_clause}`);
  }

  const lines: string[] = [];
  lines.push("-- Generated by Flo (Eterc).");
  lines.push("--");
  lines.push("-- SQLite dialect notes:");
  lines.push(
    "--   * INT PRIMARY KEY AUTO_INCREMENT -> INTEGER PRIMARY KEY AUTOINCREMENT"
  );
  lines.push(
    "--   * optional numeric columns default to 0 (no-NULL sentinel convention)"
  );
  lines.push("--   * identifiers use backticks, which SQLite accepts");
  lines.push("");
  lines.push(`CREATE TABLE \`${data.module_folder_name}\` (`);
  lines.push(columns.join(",\n"));
  lines.push(");");
  lines.push("");
  return lines.join("\n");
}
