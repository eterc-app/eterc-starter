function parse_collection_order(value: unknown): CmsCollectionSort[] {
  if (typeof value !== "string" || value.trim() === "") return [];
  try {
    const parsed: unknown = JSON.parse(value);
    if (!Array.isArray(parsed)) return [];
    return parsed.filter(
      (item): item is CmsCollectionSort =>
        Boolean(item) &&
        typeof item === "object" &&
        typeof item.field === "string" &&
        (item.direction === "asc" || item.direction === "desc")
    );
  } catch {
    return [];
  }
}

function normalize_collection_order(
  value: unknown,
  availableFields: Set<string>
): CmsCollectionSort[] {
  if (value === undefined) return [];
  if (!Array.isArray(value)) {
    throw new EtHttpError(400, "Default ordering must be a list of fields.");
  }
  const seen = new Set<string>();
  return value.map((item) => {
    if (!item || typeof item !== "object" || Array.isArray(item)) {
      throw new EtHttpError(400, "A default ordering rule is invalid.");
    }
    const rule = item as Record<string, unknown>;
    const field = String(rule.field ?? "").trim();
    if (!is_safe_identifier(field) || !availableFields.has(field)) {
      throw new EtHttpError(400, `Default ordering field '${field}' is not a storage field in this collection.`);
    }
    if (seen.has(field)) {
      throw new EtHttpError(400, `Default ordering field '${field}' is listed more than once.`);
    }
    if (rule.direction !== "asc" && rule.direction !== "desc") {
      throw new EtHttpError(400, `Default ordering direction for '${field}' must be ascending or descending.`);
    }
    seen.add(field);
    return { field, direction: rule.direction };
  });
}

function collection_ordering_mode(
  value: unknown,
  hasSystemSort: boolean
): CmsCollectionOrderingMode {
  const mode = value ?? (hasSystemSort ? "manual" : "default");
  if (mode !== "default" && mode !== "manual" && mode !== "fields") {
    throw new EtHttpError(400, "Choose a valid collection ordering mode.");
  }
  if (mode === "manual" && !hasSystemSort) {
    throw new EtHttpError(400, "Manual ordering requires the collection Sort field.");
  }
  return mode;
}

function parse_json_object(value: unknown): Record<string, unknown> {
  if (typeof value !== "string" || value.trim() === "") return {};
  try {
    const parsed = JSON.parse(value) as unknown;
    return parsed && typeof parsed === "object" && !Array.isArray(parsed)
      ? (parsed as Record<string, unknown>)
      : {};
  } catch {
    return {};
  }
}

function assert_identifier(value: string, label: string): void {
  if (!is_safe_identifier(value)) {
    throw new EtHttpError(400, `${label} must start with a letter or underscore and contain only letters, numbers and underscores.`);
  }
}

function assert_collection_name(name: string): void {
  assert_identifier(name, "Collection name");
  if (RESERVED_PREFIXES.some((prefix) => name.startsWith(prefix))) {
    throw new EtHttpError(400, "That collection name is reserved by the platform.");
  }
}

function bounded_index_name(prefix: string, collectionName: string, fieldName: string): string {
  const raw = `${prefix}_${collectionName}_${fieldName}`;
  if (raw.length <= 60) return raw;
  const digest = crypto.createHash("sha1").update(raw).digest("hex").slice(0, 8);
  return `${raw.slice(0, 50)}_${digest}`;
}

function unique_index_name(collectionName: string, fieldName: string): string {
  return bounded_index_name("cms_uq", collectionName, fieldName);
}

async function index_exists_mysql(
  name: string,
  adapter: SqlClient = activeDbAdapter
): Promise<boolean> {
  if (client_dialect(adapter) !== "mysql") return false;
  const result = await query_rows<{ name: string }>(
    "SELECT index_name AS name FROM information_schema.statistics WHERE table_schema = DATABASE() AND index_name = ? LIMIT 1",
    [name],
    adapter
  );
  return result.length > 0;
}

async function create_index(
  name: string,
  collectionName: string,
  columns: string[],
  unique: boolean,
  adapter: SqlClient = activeDbAdapter
): Promise<void> {
  const prefix = unique ? "CREATE UNIQUE INDEX" : "CREATE INDEX";
  const ifNotExists = client_dialect(adapter) === "mysql" ? "" : " IF NOT EXISTS";
  try {
    await execute_statement(
      `${prefix}${ifNotExists} ${quote_identifier(name)} ON ${quote_identifier(
        collectionName
      )} (${columns.map(quote_identifier).join(", ")})`,
      [],
      adapter
    );
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    if (
      client_dialect(adapter) === "mysql" &&
      /duplicate key name|already exists/i.test(message)
    ) {
      return;
    }
    throw error;
  }
}

async function create_unique_index(
  collectionName: string,
  fieldName: string,
  adapter: SqlClient = activeDbAdapter
): Promise<void> {
  await create_index(
    unique_index_name(collectionName, fieldName),
    collectionName,
    [fieldName],
    true,
    adapter
  );
}

async function drop_unique_index(
  collectionName: string,
  fieldName: string,
  adapter: SqlClient = activeDbAdapter
): Promise<void> {
  const name = unique_index_name(collectionName, fieldName);
  if (client_dialect(adapter) === "mysql") {
    if (!(await index_exists_mysql(name, adapter))) return;
    await execute_statement(
      `DROP INDEX ${quote_identifier(name)} ON ${quote_identifier(collectionName)}`,
      [],
      adapter
    );
    return;
  }
  await execute_statement(
    `DROP INDEX IF EXISTS ${quote_identifier(name)}`,
    [],
    adapter
  );
}

