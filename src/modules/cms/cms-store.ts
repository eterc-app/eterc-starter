export async function add_field(
  collectionName: string,
  input: CmsFieldInput
): Promise<CmsField> {
  const { collection, fields } = await require_collection(collectionName);
  if (collection.system) {
    throw new EtHttpError(403, "System collections cannot be changed.");
  }
  const name = String(input.name ?? "").trim();
  assert_identifier(name, "Field name");
  if (fields.some((field) => field.name === name)) {
    throw new EtHttpError(409, `Field '${name}' already exists in '${collectionName}'.`);
  }
  if (RESERVED_PREFIXES.some((prefix) => name.startsWith(prefix))) {
    throw new EtHttpError(400, "That field name is reserved by the platform.");
  }

  const field = normalize_field({ ...input, name });
  const knownFields = [...fields, {
    ...field,
    id: 0,
    collection_id: collection.id,
    sort: 0,
    created_at: 0,
    updated_at: 0,
  }];
  field.validation = normalize_field_rule(field.validation, knownFields);
  field.conditions = normalize_field_conditions(field.conditions, knownFields);
  assert_hidden_clear_is_writable(field);
  assert_group_reference(fields, field.group, field.name);
  const metadataOnly = field.type === "alias";
  const ddl = metadataOnly ? "" : default_field_sql(field, false);
  try {
    return await db.transaction(async (tx) => {
      if (!metadataOnly) {
        await execute_statement(
          `ALTER TABLE ${quote_identifier(collectionName)} ADD COLUMN ${ddl}`,
          [],
          tx
        );
        if (field.unique) {
          await create_unique_index(collectionName, field.name, tx);
        }
      }
      const now = nowSeconds();
      const sort = fields.reduce((max, item) => Math.max(max, item.sort), 0) + 1;
      const fieldId = await tx.insert(
        {
          collection_id: collection.id,
          name: field.name,
          label: field.label,
          type: field.type,
          interface: field.interface,
          options: JSON.stringify(field.options),
          required: field.required ? 1 : 0,
          unique: field.unique ? 1 : 0,
          hidden: field.hidden ? 1 : 0,
          readonly: field.readonly ? 1 : 0,
          clear_hidden_value_on_save: field.clear_hidden_value_on_save ? 1 : 0,
          group: field.group,
          validation: JSON.stringify(field.validation),
          validation_message: field.validation_message,
          conditions: JSON.stringify(field.conditions),
          display_options: JSON.stringify(field.display_options),
          sort,
          created_at: now,
          updated_at: now,
        },
        "cms_fields"
      );
      const rows = await query_rows(
        "SELECT * FROM cms_fields WHERE id = ?",
        [fieldId],
        tx
      );
      return fieldFromRow(rows[0]);
    });
  } catch (error) {
    if (error instanceof EtHttpError) throw error;
    throw new EtHttpError(
      409,
      `The field '${field.name}' could not be added. ${
        error instanceof Error ? error.message : ""
      }`.trim()
    );
  }
}

export async function update_field(
  collectionName: string,
  fieldName: string,
  patch: Partial<
    Pick<
      CmsField,
      | "label"
      | "type"
      | "interface"
      | "options"
      | "required"
      | "unique"
      | "hidden"
      | "readonly"
      | "clear_hidden_value_on_save"
      | "group"
      | "validation"
      | "validation_message"
      | "conditions"
      | "display_options"
    >
  >
): Promise<CmsField> {
  const { collection, fields } = await require_collection(collectionName);
  if (collection.system) {
    throw new EtHttpError(403, "System collections cannot be changed.");
  }
  const field = fields.find((item) => item.name === fieldName);
  if (!field) throw new EtHttpError(404, `Field '${fieldName}' was not found.`);
  if (field.name === "id") {
    throw new EtHttpError(403, "The primary key field cannot be changed.");
  }
  if (patch.type !== undefined && patch.type !== field.type) {
    throw new EtHttpError(
      400,
      "A field's storage type cannot be changed after creation."
    );
  }

  const currentAlias = field.type === "alias" || cms_is_alias_interface(field.interface);
  const requestedType =
    patch.type && CMS_FIELD_TYPES.includes(patch.type) ? patch.type : field.type;
  const requestedInterface = patch.interface ?? field.interface;
  if (
    patch.interface !== undefined &&
    patch.interface !== field.interface &&
    !cms_interface_definition(requestedInterface).types.includes(field.type)
  ) {
    throw new EtHttpError(
      400,
      `The '${requestedInterface}' interface does not support the '${field.type}' storage type.`
    );
  }
  const requestedAlias =
    requestedType === "alias" || cms_is_alias_interface(requestedInterface);
  if (currentAlias !== requestedAlias) {
    throw new EtHttpError(
      400,
      "A metadata-only field cannot be converted into a database column, or the reverse. Delete and recreate it instead."
    );
  }
  const nextType = requestedAlias ? "alias" : requestedType;
  const nextInterface = requestedAlias
    ? cms_is_alias_interface(requestedInterface)
      ? requestedInterface
      : field.interface
    : requestedInterface;
  const nextGroup =
    patch.group === undefined
      ? field.group
      : String(patch.group ?? "").trim() === ""
        ? null
        : String(patch.group).trim();
  assert_group_reference(fields, nextGroup, field.name);
  const nextUnique = requestedAlias ? false : (patch.unique ?? field.unique);
  const nextRequired = requestedAlias ? false : (patch.required ?? field.required);
  const nextHidden = patch.hidden ?? field.hidden;
  const nextClearHiddenValue =
    Boolean(patch.clear_hidden_value_on_save ?? field.clear_hidden_value_on_save) &&
    nextHidden;
  const validation = patch.validation === undefined
    ? field.validation
    : normalize_field_rule(patch.validation, fields);
  const conditions = patch.conditions === undefined
    ? field.conditions
    : normalize_field_conditions(patch.conditions, fields);
  if (
    patch.validation_message !== undefined &&
    typeof patch.validation_message !== "string"
  ) {
    throw new EtHttpError(400, "A custom validation message must be text.");
  }
  const validationMessage =
    patch.validation_message === undefined
      ? field.validation_message
      : patch.validation_message.slice(0, 500);
  const displayOptions =
    patch.display_options === undefined
      ? field.display_options
      : normalize_display_options(patch.display_options);
  assert_hidden_clear_is_writable({
    ...field,
    required: nextRequired,
    options: patch.options ?? field.options,
    hidden: nextHidden,
    clear_hidden_value_on_save: nextClearHiddenValue,
    conditions,
  });
  try {
    return await db.transaction(async (tx) => {
      if (!requestedAlias) {
        if (nextUnique && !field.unique) {
          await create_unique_index(collectionName, field.name, tx);
        }
        if (!nextUnique && field.unique) {
          await drop_unique_index(collectionName, field.name, tx);
        }
      }
      await execute_statement(
        `UPDATE cms_fields
         SET label = ?, type = ?, interface = ?, options = ?, required = ?, "unique" = ?, hidden = ?, readonly = ?, clear_hidden_value_on_save = ?, "group" = ?, validation = ?, validation_message = ?, conditions = ?, display_options = ?, updated_at = ?
         WHERE id = ?`,
        [
          patch.label ?? field.label,
          nextType,
          nextInterface,
          JSON.stringify(patch.options ?? field.options),
          nextRequired ? 1 : 0,
          nextUnique ? 1 : 0,
          nextHidden ? 1 : 0,
          (patch.readonly ?? field.readonly) ? 1 : 0,
          nextClearHiddenValue ? 1 : 0,
          nextGroup,
          JSON.stringify(validation),
          validationMessage,
          JSON.stringify(conditions),
          JSON.stringify(displayOptions),
          nowSeconds(),
          field.id,
        ],
        tx
      );
      const rows = await query_rows(
        "SELECT * FROM cms_fields WHERE id = ?",
        [field.id],
        tx
      );
      return fieldFromRow(rows[0]);
    });
  } catch (error) {
    if (error instanceof EtHttpError) throw error;
    throw new EtHttpError(
      409,
      `The field '${field.name}' could not be updated. ${
        error instanceof Error ? error.message : ""
      }`.trim()
    );
  }
}

export async function reorder_fields(
  collectionName: string,
  fieldNames: string[]
): Promise<CmsField[]> {
  const { collection, fields } = await require_collection(collectionName);
  if (collection.system) {
    throw new EtHttpError(403, "System collections cannot be changed.");
  }
  if (
    fieldNames.length !== fields.length ||
    new Set(fieldNames).size !== fieldNames.length ||
    fieldNames.some((name) => !fields.some((field) => field.name === name))
  ) {
    throw new EtHttpError(400, "The field order must include every collection field exactly once.");
  }

  const now = nowSeconds();
  await db.transaction(async (tx) => {
    for (let index = 0; index < fieldNames.length; index += 1) {
      await execute_statement(
        "UPDATE cms_fields SET sort = ?, updated_at = ? WHERE collection_id = ? AND name = ?",
        [index + 1, now, collection.id, fieldNames[index]],
        tx
      );
    }
  });

  return field_rows(collection.id);
}

export async function delete_field(
  collectionName: string,
  fieldName: string
): Promise<void> {
  const { collection, fields } = await require_collection(collectionName);
  if (collection.system) {
    throw new EtHttpError(403, "System collections cannot be changed.");
  }
  const field = fields.find((item) => item.name === fieldName);
  if (!field) throw new EtHttpError(404, `Field '${fieldName}' was not found.`);
  if (field.name === "id") {
    throw new EtHttpError(403, "The primary key field cannot be deleted.");
  }
  const metadataOnly = field.type === "alias" || cms_is_alias_interface(field.interface);
  try {
    await db.transaction(async (tx) => {
      for (const other of fields) {
        if (other.id === field.id) continue;
        const conditions = other.conditions
          .map((condition) => ({
            ...condition,
            rule: remove_field_from_rule(condition.rule, field.name),
          }))
          .filter((condition) => condition.rule.conditions.length > 0);
        await execute_statement(
          `UPDATE cms_fields SET validation = ?, conditions = ?, updated_at = ?
           WHERE id = ?`,
          [
            JSON.stringify(remove_field_from_rule(other.validation, field.name)),
            JSON.stringify(conditions),
            nowSeconds(),
            other.id,
          ],
          tx
        );
      }
      if (!metadataOnly) {
        await drop_unique_index(collectionName, field.name, tx);
        await execute_statement(
          `ALTER TABLE ${quote_identifier(collectionName)} DROP COLUMN ${quote_identifier(field.name)}`,
          [],
          tx
        );
      }
      await execute_statement("DELETE FROM cms_fields WHERE id = ?", [field.id], tx);
      await execute_statement(
        `UPDATE cms_fields SET "group" = NULL WHERE collection_id = ? AND "group" = ?`,
        [collection.id, field.name],
        tx
      );
      const defaultOrder = collection.default_order.filter(
        (rule) => rule.field !== field.name
      );
      const deletedSystemSort =
        field.options._eterc_system_field === "sort" ||
        (field.name === "sort" &&
          field.type === "integer" &&
          field.interface === "number");
      const nextMode =
        (deletedSystemSort && collection.ordering_mode === "manual") ||
        (collection.ordering_mode === "fields" && defaultOrder.length === 0)
          ? "default"
          : collection.ordering_mode;
      await execute_statement(
        "UPDATE cms_collections SET default_order = ?, ordering_mode = ?, updated_at = ? WHERE id = ?",
        [JSON.stringify(defaultOrder), nextMode, nowSeconds(), collection.id],
        tx
      );
      if (!metadataOnly) {
        await remove_field_from_policies(collectionName, field.name, tx);
      }
    });
  } catch (error) {
    throw new EtHttpError(
      409,
      `The database could not drop '${field.name}'. It may be used by an index or trigger. ${
        error instanceof Error ? error.message : ""
      }`.trim()
    );
  }
}

function normalize_field(input: CmsFieldInput): Required<CmsFieldInput> {
  const requestedType =
    input.type && CMS_FIELD_TYPES.includes(input.type) ? input.type : "string";
  const requestedInterface = input.interface ?? cms_field_interface(requestedType);
  const metadataOnly =
    requestedType === "alias" || cms_is_alias_interface(requestedInterface);
  if (
    !metadataOnly &&
    !cms_interface_definition(requestedInterface).types.includes(requestedType)
  ) {
    throw new EtHttpError(
      400,
      `The '${requestedInterface}' interface does not support the '${requestedType}' storage type.`
    );
  }
  const type: CmsFieldType = metadataOnly ? "alias" : requestedType;
  const group = String(input.group ?? "").trim();
  if (
    input.validation_message !== undefined &&
    typeof input.validation_message !== "string"
  ) {
    throw new EtHttpError(400, "A custom validation message must be text.");
  }
  return {
    name: String(input.name ?? "").trim(),
    label: String(input.label ?? humanize_name(String(input.name ?? ""))),
    type,
    interface: metadataOnly
      ? cms_is_alias_interface(requestedInterface)
        ? requestedInterface
        : "raw_group"
      : requestedInterface,
    options: input.options ?? {},
    required: metadataOnly ? false : Boolean(input.required),
    unique: metadataOnly ? false : Boolean(input.unique),
    hidden: Boolean(input.hidden),
    readonly: Boolean(input.readonly),
    clear_hidden_value_on_save:
      Boolean(input.hidden) && Boolean(input.clear_hidden_value_on_save),
    group: group === "" ? null : group,
    validation: input.validation ?? empty_field_rule(),
    validation_message: String(input.validation_message ?? "").slice(0, 500),
    conditions: input.conditions ?? [],
    display_options: normalize_display_options(input.display_options ?? {}),
  };
}

function normalize_display_options(value: unknown): CmsFieldDisplayOptions {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new EtHttpError(400, "Field display options must be an object.");
  }
  const options = value as Record<string, unknown>;
  return {
    prefix: typeof options.prefix === "string" ? options.prefix.slice(0, 100) : "",
    suffix: typeof options.suffix === "string" ? options.suffix.slice(0, 100) : "",
  };
}

function assert_group_reference(
  fields: CmsField[],
  group: string | null,
  fieldName: string
): void {
  if (!group) return;
  if (group === fieldName) {
    throw new EtHttpError(400, "A field cannot be grouped inside itself.");
  }
  const parent = fields.find((field) => field.name === group);
  if (!parent || !cms_is_group_interface(parent.interface)) {
    throw new EtHttpError(400, `Group '${group}' is not a group field in this collection.`);
  }
}

function visible_fields(fields: CmsField[], includeHidden = true): CmsField[] {
  return includeHidden ? fields : fields.filter((field) => !field.hidden);
}

function order_field(
  fields: CmsField[],
  sort?: string,
  primaryKey = "id"
): CmsField {
  const storageFields = fields.filter((field) => field.type !== "alias");
  const requested = sort
    ? storageFields.find((field) => field.name === sort)
    : undefined;
  if (requested) return requested;
  return (
    storageFields.find((field) => field.name === primaryKey) ??
    storageFields.find((field) => field.name === "id") ??
    storageFields[0] ??
    fields[0]
  );
}

/**
 * SQLite and MySQL expose `instr()`, while PostgreSQL needs `position()`.
 */
function contains_sql(column: string, needle = "?"): string {
  return activeDbAdapter.dialect === "postgres"
    ? `position(${needle} in ${column}) > 0`
    : `instr(${column}, ${needle}) > 0`;
}

function build_filter_clauses(
  fields: CmsField[],
  filter: Record<string, unknown>,
  byName: Map<string, CmsField>
): { clauses: string[]; params: unknown[] } {
  const clauses: string[] = [];
  const params: unknown[] = [];

  for (const [key, value] of Object.entries(filter)) {
    if (key === "_and" || key === "_or") {
      if (!Array.isArray(value)) {
        throw new EtHttpError(400, `Filter '${key}' must be an array.`);
      }
      const groups = value
        .filter((entry): entry is Record<string, unknown> =>
          Boolean(entry) && typeof entry === "object" && !Array.isArray(entry)
        )
        .map((entry) => build_filter_clauses(fields, entry, byName));
      if (groups.length === 0) {
        if (key === "_or") clauses.push("1 = 0");
        continue;
      }
      const joined = groups
        .map((group) =>
          group.clauses.length > 0 ? `(${group.clauses.join(" AND ")})` : "1 = 1"
        )
        .join(key === "_and" ? " AND " : " OR ");
      clauses.push(`(${joined})`);
      for (const group of groups) params.push(...group.params);
      continue;
    }

    const field = byName.get(key);
    if (!field) {
      throw new EtHttpError(400, `Unknown filter field '${key}'.`);
    }
    const column = quote_identifier(field.name);

    if (value === null) {
      clauses.push(`${column} IS NULL`);
      continue;
    }
    if (typeof value === "object" && !Array.isArray(value)) {
      for (const [operator, operand] of Object.entries(value as Record<string, unknown>)) {
        switch (operator) {
          case "_eq":
            if (operand === null) {
              clauses.push(`${column} IS NULL`);
            } else {
              clauses.push(`${column} = ?`);
              params.push(operand);
            }
            break;
          case "_neq":
            if (operand === null) {
              clauses.push(`${column} IS NOT NULL`);
            } else {
              clauses.push(`(${column} IS NULL OR ${column} != ?)`);
              params.push(operand);
            }
            break;
          case "_contains":
            clauses.push(contains_sql(column));
            params.push(String(operand));
            break;
          case "_not_contains":
            clauses.push(`(${column} IS NULL OR NOT (${contains_sql(column)}))`);
            params.push(String(operand));
            break;
          case "_icontains":
            clauses.push(
              contains_sql(`lower(${column})`, "lower(?)")
            );
            params.push(String(operand));
            break;
          case "_starts_with":
            clauses.push(`substr(${column}, 1, length(?)) = ?`);
            params.push(String(operand), String(operand));
            break;
          case "_not_starts_with":
            clauses.push(
              `(${column} IS NULL OR substr(${column}, 1, length(?)) != ?)`
            );
            params.push(String(operand), String(operand));
            break;
          case "_not_istarts_with":
            clauses.push(
              `(${column} IS NULL OR substr(lower(${column}), 1, length(lower(?))) != lower(?))`
            );
            params.push(String(operand), String(operand));
            break;
          case "_ends_with":
            clauses.push(`substr(${column}, -length(?)) = ?`);
            params.push(String(operand), String(operand));
            break;
          case "_not_ends_with":
            clauses.push(
              `(${column} IS NULL OR substr(${column}, -length(?)) != ?)`
            );
            params.push(String(operand), String(operand));
            break;
          case "_iends_with":
            clauses.push(
              `substr(lower(${column}), -length(lower(?))) = lower(?)`
            );
            params.push(String(operand), String(operand));
            break;
          case "_not_iends_with":
            clauses.push(
              `(${column} IS NULL OR substr(lower(${column}), -length(lower(?))) != lower(?))`
            );
            params.push(String(operand), String(operand));
            break;
          case "_ieq":
            clauses.push(`lower(${column}) = lower(?)`);
            params.push(operand);
            break;
          case "_nieq":
            clauses.push(`(${column} IS NULL OR lower(${column}) != lower(?))`);
            params.push(operand);
            break;
          case "_empty":
            clauses.push(`${column} = ''`);
            break;
          case "_nempty":
            clauses.push(`(${column} IS NOT NULL AND ${column} != '')`);
            break;
          case "_gt":
            clauses.push(`${column} > ?`);
            params.push(operand);
            break;
          case "_gte":
            clauses.push(`${column} >= ?`);
            params.push(operand);
            break;
          case "_lt":
            clauses.push(`${column} < ?`);
            params.push(operand);
            break;
          case "_lte":
            clauses.push(`${column} <= ?`);
            params.push(operand);
            break;
          case "_null":
            clauses.push(operand ? `${column} IS NULL` : `${column} IS NOT NULL`);
            break;
          case "_nnull":
            clauses.push(operand ? `${column} IS NOT NULL` : `${column} IS NULL`);
            break;
          case "_in": {
            const values = Array.isArray(operand) ? operand : [operand];
            if (values.length === 0) {
              clauses.push("1 = 0");
              break;
            }
            const nonNull = values.filter((value) => value !== null);
            const parts: string[] = [];
            if (nonNull.length !== values.length) parts.push(`${column} IS NULL`);
            if (nonNull.length > 0) {
              parts.push(`${column} IN (${nonNull.map(() => "?").join(", ")})`);
              params.push(...nonNull);
            }
            clauses.push(parts.length === 1 ? parts[0] : `(${parts.join(" OR ")})`);
            break;
          }
          case "_not_in": {
            const values = Array.isArray(operand) ? operand : [operand];
            if (values.length === 0) {
              clauses.push("1 = 1");
              break;
            }
            const nonNull = values.filter((value) => value !== null);
            const includesNull = nonNull.length !== values.length;
            if (nonNull.length > 0) {
              const notInClause = `${column} NOT IN (${nonNull.map(() => "?").join(", ")})`;
              params.push(...nonNull);
              clauses.push(
                includesNull
                  ? `(${column} IS NOT NULL AND ${notInClause})`
                  : `(${column} IS NULL OR ${notInClause})`
              );
            } else {
              clauses.push(`${column} IS NOT NULL`);
            }
            break;
          }
          default:
            throw new EtHttpError(400, `Unsupported filter operator '${operator}'.`);
        }
      }
      continue;
    }
    if (Array.isArray(value)) {
      throw new EtHttpError(400, `Use the _in operator for array values on '${key}'.`);
    }
    clauses.push(`${column} = ?`);
    params.push(value);
  }

  return { clauses, params };
}

function build_where(
  fields: CmsField[],
  search: string | undefined,
  filter: Record<string, unknown> | undefined
): { sql: string; params: unknown[] } {
  const clauses: string[] = [];
  const params: unknown[] = [];
  const byName = new Map(fields.map((field) => [field.name, field]));

  if (search && search.trim() !== "") {
    const textFields = fields.filter(
      (field) =>
        !field.hidden &&
        field.type !== "alias" &&
        (field.type === "string" || field.type === "text" || field.type === "select")
    );
    if (textFields.length > 0) {
      clauses.push(
        `(${textFields
          .map((field) => `${quote_identifier(field.name)} LIKE ?`)
          .join(" OR ")})`
      );
      for (let index = 0; index < textFields.length; index += 1) {
        params.push(`%${search.trim()}%`);
      }
    }
  }

  if (filter && typeof filter === "object") {
    const built = build_filter_clauses(fields, filter, byName);
    clauses.push(...built.clauses);
    params.push(...built.params);
  }

  return {
    sql: clauses.length > 0 ? `WHERE ${clauses.join(" AND ")}` : "",
    params,
  };
}

export async function list_records(
  collectionName: string,
  options: CmsRecordListOptions = {}
): Promise<CmsRecordListResult> {
  const { collection, fields } = await require_collection(collectionName);
  const page = Math.max(1, Number(options.page ?? 1) || 1);
  const configuredMax = Math.min(
    500,
    Math.max(1, Number(get_runtime_config().cms.max_page_size) || MAX_LIMIT)
  );
  const limit = Math.min(
    configuredMax,
    Math.max(1, Number(options.limit ?? DEFAULT_LIMIT) || DEFAULT_LIMIT)
  );
  const sortField = system_sort_field(fields);
  const explicitSort = options.sort?.trim();
  const orderingMode = collection_ordering_mode(
    collection.ordering_mode,
    Boolean(sortField)
  );
  const sortRules: Array<{
    field: string;
    direction: "ASC" | "DESC";
    nullsLast: boolean;
  }> = explicitSort
    ? [
        {
          field: order_field(fields, explicitSort, collection.primary_key).name,
          direction:
            String(options.direction ?? "desc").toLowerCase() === "asc"
              ? "ASC"
              : "DESC",
          nullsLast:
            sortField?.name ===
            order_field(fields, explicitSort, collection.primary_key).name,
        },
      ]
    : orderingMode === "fields"
      ? collection.default_order
          .filter((rule) => fields.some((field) => field.name === rule.field && field.type !== "alias"))
          .map((rule) => ({
            field: rule.field,
            direction:
              String(options.direction ?? rule.direction).toLowerCase() === "asc"
                ? "ASC"
                : "DESC",
            nullsLast: true,
          }))
      : orderingMode === "manual" && sortField
        ? [
            {
              field: sortField.name,
              direction:
                String(options.direction ?? "asc").toLowerCase() === "asc"
                  ? "ASC"
                  : "DESC",
              nullsLast: true,
            },
          ]
        : [
            {
              field: collection.primary_key,
              direction:
                String(options.direction ?? "desc").toLowerCase() === "asc"
                  ? "ASC"
                  : "DESC",
              nullsLast: false,
            },
          ];
  if (sortRules.length === 0) {
    sortRules.push({
      field: collection.primary_key,
      direction:
        String(options.direction ?? "desc").toLowerCase() === "asc"
          ? "ASC"
          : "DESC",
      nullsLast: false,
    });
  }
  const filter = options.access_filter
    ? options.filter
      ? { _and: [options.filter, options.access_filter] }
      : options.access_filter
    : options.filter;
  const where = build_where(fields, options.search, filter);
  const offset = (page - 1) * limit;
  const orderByParts = sortRules.flatMap((rule) => [
    ...(rule.nullsLast
      ? [`${quote_identifier(rule.field)} IS NULL ASC`]
      : []),
    `${quote_identifier(rule.field)} ${rule.direction}`,
  ]);
  if (!sortRules.some((rule) => rule.field === collection.primary_key)) {
    orderByParts.push(`${quote_identifier(collection.primary_key)} ASC`);
  }
  const orderBy = orderByParts.join(", ");

  const totalRows = await query_rows<{ count: number | string }>(
    `SELECT COUNT(*) AS count FROM ${quote_identifier(collectionName)} ${where.sql}`,
    where.params
  );
  const total = Number(totalRows[0]?.count ?? 0);

  const rows = await query_rows(
    `SELECT * FROM ${quote_identifier(collectionName)}
     ${where.sql}
     ORDER BY ${orderBy}
     LIMIT ? OFFSET ?`,
    [...where.params, limit, offset]
  );

  return {
    rows: rows.map(sanitize_row),
    total,
    page,
    limit,
    pages: Math.max(1, Math.ceil(total / limit)),
  };
}

export async function get_record(
  collectionName: string,
  id: string | number
): Promise<Record<string, unknown>> {
  const { collection } = await require_collection(collectionName);
  const rows = await query_rows(
    `SELECT * FROM ${quote_identifier(collectionName)} WHERE ${quote_identifier(
      collection.primary_key
    )} = ? LIMIT 1`,
    [id]
  );
  const row = rows[0];
  if (!row) throw new EtHttpError(404, "Record not found.");
  return sanitize_row(row);
}

export async function create_record(
  collectionName: string,
  input: Record<string, unknown>,
  actorUserId: number | null = null,
  options: { allowSortOverride?: boolean } = {}
): Promise<Record<string, unknown>> {
  const { collection, fields } = await require_collection(collectionName);
  const sortField = system_sort_field(fields);
  const sortInput =
    sortField && options.allowSortOverride ? input[sortField.name] : undefined;
  const writeInput = sortField
    ? Object.fromEntries(
        Object.entries(input).filter(([key]) => key !== sortField.name)
      )
    : input;
  const values = prepare_write_values(fields, writeInput, false, collection.primary_key);
  let explicitSort: number | undefined;
  if (
    sortField &&
    sortInput !== undefined &&
    sortInput !== null &&
    sortInput !== ""
  ) {
    const parsed = Number(sortInput);
    if (!Number.isSafeInteger(parsed)) {
      throw new EtHttpError(422, `Field '${sortField.label || sortField.name}' must be an integer.`);
    }
    explicitSort = parsed;
  }
  const createdByField = fields.find(
    (field) =>
      field.name !== collection.primary_key &&
      field.type !== "alias" &&
      field.readonly &&
      (field.options?._eterc_system_field === "user_created" ||
        field.name === "user_created")
  );
  if (createdByField) values[createdByField.name] = actorUserId;
  const validationValues = Object.fromEntries(
    fields
      .filter((field) => field.type !== "alias")
      .map((field) => [field.name, field.options.default ?? null])
  );
  Object.assign(validationValues, values);
  validate_effective_record(fields, validationValues, values);
  try {
    // The adapter transaction allows `INSERT ... RETURNING` rows to be read
    // directly; the Db facade only exposes mutation metadata for writes.
    return await activeDbAdapter.transaction(async (tx) => {
      if (sortField) {
        if (explicitSort !== undefined) {
          values[sortField.name] = explicitSort;
        } else {
          const maximum = await query_rows<{ maximum: number | string | null }>(
            `SELECT MAX(${quote_identifier(sortField.name)}) AS maximum
             FROM ${quote_identifier(collectionName)}`,
            [],
            tx
          );
          const next = Number(maximum[0]?.maximum ?? 0) + 1;
          if (!Number.isSafeInteger(next)) {
            throw new EtHttpError(409, "No available integer sort position remains.");
          }
          values[sortField.name] = next;
        }
      }

      // MySQL has no INSERT ... RETURNING. Integer keys come back as
      // insertId; UUID keys are generated here so the row can be read back.
      const supportsReturning = activeDbAdapter.dialect !== "mysql";
      if (!supportsReturning && values[collection.primary_key] === undefined) {
        const primaryField = fields.find(
          (field) => field.name === collection.primary_key
        );
        if (
          primaryField &&
          primaryField.type === "string" &&
          primaryField.readonly
        ) {
          values[collection.primary_key] = crypto.randomUUID();
        }
      }
      const currentColumns = Object.keys(values);
      const insertBase =
        currentColumns.length === 0
          ? `INSERT INTO ${quote_identifier(collectionName)} DEFAULT VALUES`
          : `INSERT INTO ${quote_identifier(collectionName)}
             (${currentColumns.map(quote_identifier).join(", ")})
             VALUES (${currentColumns.map(() => "?").join(", ")})`;
      const params = currentColumns.map((column) => values[column]);

      let row: Row | undefined;
      if (supportsReturning) {
        const rows = await query_rows(
          `${insertBase} RETURNING *`,
          params,
          tx
        );
        row = rows[0];
      } else {
        const result = await execute_statement(insertBase, params, tx);
        const insertedKey =
          values[collection.primary_key] ?? result.lastInsertRowid;
        const rows = await query_rows(
          `SELECT * FROM ${quote_identifier(collectionName)}
           WHERE ${quote_identifier(collection.primary_key)} = ? LIMIT 1`,
          [insertedKey],
          tx
        );
        row = rows[0];
      }
      if (!row) {
        throw new EtHttpError(500, "The record was created but could not be read back.");
      }
      return sanitize_row(row);
    });
  } catch (error) {
    throw database_error(error);
  }
}

export async function reorder_records(
  collectionName: string,
  page: number,
  recordIds: Array<string | number>,
  limit = 20
): Promise<void> {
  const { collection, fields } = await require_collection(collectionName);
  if (collection.system) {
    throw new EtHttpError(403, "System collections cannot be reordered.");
  }
  const sortField = system_sort_field(fields);
  if (!sortField) {
    throw new EtHttpError(400, "This collection does not have a Sort field.");
  }
  if (
    collection_ordering_mode(collection.ordering_mode, true) === "fields"
  ) {
    throw new EtHttpError(
      400,
      "Manual reordering is disabled while field-based ordering is active."
    );
  }
  if (!Number.isSafeInteger(page) || page < 1 || !Number.isSafeInteger(limit) || limit < 1) {
    throw new EtHttpError(400, "A valid page is required to reorder records.");
  }
  if (
    !Array.isArray(recordIds) ||
    recordIds.length === 0 ||
    recordIds.length > limit ||
    new Set(recordIds.map(String)).size !== recordIds.length
  ) {
    throw new EtHttpError(400, "The ordered record ids are invalid.");
  }

  const offset = (page - 1) * limit;
  if (!Number.isSafeInteger(offset)) {
    throw new EtHttpError(400, "The requested page is too large to reorder.");
  }
  const table = quote_identifier(collectionName);
  const primaryKey = quote_identifier(collection.primary_key);
  const sortColumn = quote_identifier(sortField.name);
  type SortRow = { id: string | number; sort_value: number | null };
  const pageSql = `SELECT ${primaryKey} AS id, ${sortColumn} AS sort_value
     FROM ${table}
     ORDER BY ${sortColumn} IS NULL ASC, ${sortColumn} ASC, ${primaryKey} ASC
     LIMIT ? OFFSET ?`;
  const updateSql = `UPDATE ${table} SET ${sortColumn} = ? WHERE ${primaryKey} = ?`;

  try {
    await db.transaction(async (tx) => {
      const pageRows = await query_rows<SortRow>(pageSql, [limit, offset], tx);
      if (
        pageRows.length !== recordIds.length ||
        pageRows.some((row) => !recordIds.some((id) => String(id) === String(row.id)))
      ) {
        throw new EtHttpError(409, "The record list changed. Refresh and try reordering again.");
      }

      const rowsById = new Map(pageRows.map((row) => [String(row.id), row]));
      const orderedPage = recordIds.map((id) => rowsById.get(String(id))!);
      const previousRows =
        offset > 0
          ? await query_rows<SortRow>(pageSql, [1, offset - 1], tx)
          : [];
      const nextRows = await query_rows<SortRow>(
        pageSql,
        [1, offset + pageRows.length],
        tx
      );
      const previous = previousRows[0];
      const next = nextRows[0];

      const pageHasNulls = pageRows.some((row) => row.sort_value === null);
      const previousIsNull = previous?.sort_value === null;
      const lower = previous ? Number(previous.sort_value) : 0;
      const upper =
        next && next.sort_value !== null ? Number(next.sort_value) : null;
      const available = upper === null ? Number.POSITIVE_INFINITY : upper - lower - 1;

      if (!pageHasNulls && !previousIsNull && available >= orderedPage.length) {
        const step =
          upper === null
            ? 1
            : Math.floor((upper - lower) / (orderedPage.length + 1));
        const start = upper === null ? lower + 1 : lower + step;
        if (step >= 1 && (previous || start >= 1)) {
          for (let index = 0; index < orderedPage.length; index += 1) {
            await execute_statement(
              updateSql,
              [start + index * step, orderedPage[index].id],
              tx
            );
          }
          return;
        }
      }

      const allRows = await query_rows<{ id: string | number }>(
        `SELECT ${primaryKey} AS id
         FROM ${table}
         ORDER BY ${sortColumn} IS NULL ASC, ${sortColumn} ASC, ${primaryKey} ASC`,
        [],
        tx
      );
      const allById = new Map(allRows.map((row) => [String(row.id), row]));
      const reorderedIds = allRows.map((row) => String(row.id));
      reorderedIds.splice(offset, orderedPage.length, ...recordIds.map(String));
      for (let index = 0; index < reorderedIds.length; index += 1) {
        const row = allById.get(reorderedIds[index]);
        if (!row) {
          throw new EtHttpError(409, "The record list changed. Refresh and try reordering again.");
        }
        await execute_statement(updateSql, [index + 1, row.id], tx);
      }
    });
  } catch (error) {
    throw database_error(error);
  }
}

export async function update_record(
  collectionName: string,
  id: string | number,
  input: Record<string, unknown>,
  actorUserId: number | null = null
): Promise<Record<string, unknown>> {
  const { collection, fields } = await require_collection(collectionName);
  const currentRecord = await get_record(collectionName, id);
  const sortField = system_sort_field(fields);
  const writeInput = sortField
    ? Object.fromEntries(
        Object.entries(input).filter(([key]) => key !== sortField.name)
      )
    : input;
  const values = prepare_write_values(fields, writeInput, true, collection.primary_key);
  const validationValues = { ...currentRecord, ...values };
  validate_effective_record(fields, validationValues, values);
  const updatedByField = fields.find(
    (field) =>
      field.name !== collection.primary_key &&
      field.type !== "alias" &&
      field.readonly &&
      (field.options?._eterc_system_field === "user_updated" ||
        field.name === "user_updated")
  );
  if (updatedByField) values[updatedByField.name] = actorUserId;
  if (Object.keys(values).length === 0) {
    return await get_record(collectionName, id);
  }
  if (fields.some((field) => field.name === "updated_at")) {
    values.updated_at = new Date().toISOString();
  }
  const columns = Object.keys(values);
  const sql = `UPDATE ${quote_identifier(collectionName)}
    SET ${columns.map((column) => `${quote_identifier(column)} = ?`).join(", ")}
    WHERE ${quote_identifier(collection.primary_key)} = ?`;
  try {
    const result = await execute_statement(sql, [
      ...columns.map((column) => values[column]),
      id,
    ]);
    if (result.changes === 0) {
      throw new EtHttpError(404, "Record not found.");
    }
    return await get_record(collectionName, id);
  } catch (error) {
    throw database_error(error);
  }
}

function database_error(error: unknown): EtHttpError {
  if (error instanceof EtHttpError) return error;
  const message = error instanceof Error ? error.message : "";
  if (/UNIQUE constraint failed/i.test(message)) {
    return new EtHttpError(409, "A record with that unique value already exists.");
  }
  if (/NOT NULL constraint failed/i.test(message)) {
    return new EtHttpError(422, "A required field is missing.");
  }
  if (/FOREIGN KEY constraint failed/i.test(message)) {
    return new EtHttpError(409, "This record is still referenced by another record.");
  }
  return new EtHttpError(
    500,
    message ? `The database rejected the record: ${message}` : "The record could not be saved."
  );
}

export async function delete_record(
  collectionName: string,
  id: string | number
): Promise<void> {
  const { collection } = await require_collection(collectionName);
  const result = await execute_statement(
    `DELETE FROM ${quote_identifier(collectionName)}
     WHERE ${quote_identifier(collection.primary_key)} = ?`,
    [id]
  );
  if (result.changes === 0) {
    throw new EtHttpError(404, "Record not found.");
  }
}

function prepare_write_values(
  fields: CmsField[],
  input: Record<string, unknown>,
  updating: boolean,
  primaryKey = "id"
): Record<string, unknown> {
  if (!input || typeof input !== "object" || Array.isArray(input)) {
    throw new EtHttpError(400, "A JSON object is required.");
  }
  const byName = new Map(fields.map((field) => [field.name, field]));
  const values: Record<string, unknown> = {};

  for (const [key, raw] of Object.entries(input)) {
    const field = byName.get(key);
    if (!field) {
      throw new EtHttpError(400, `Unknown field '${key}'.`);
    }
    // Alias fields are presentation or group metadata and have no SQL column.
    if (field.type === "alias") continue;
    if (field.readonly || (updating && field.name === primaryKey)) {
      if (!updating && field.readonly && raw !== undefined) {
        throw new EtHttpError(400, `Field '${key}' is read-only.`);
      }
      continue;
    }
    if (raw === undefined) continue;
    if (raw === null || raw === "") {
      if (raw === "" && !updating && !field.required) continue;
      values[field.name] = null;
      continue;
    }
    values[field.name] = coerce_value(field, raw);
  }

  return values;
}

function validate_effective_record(
  fields: CmsField[],
  record: Record<string, unknown>,
  writes: Record<string, unknown>
): void {
  const effectiveFields = new Map(
    fields.map((field) => [field.name, effective_field(field, record)])
  );
  for (const field of fields) {
    if (field.type === "alias") continue;
    const effective = effectiveFields.get(field.name)!;
    if (effective.hidden && effective.clear_hidden_value_on_save) {
      const defaultValue = field.options.default ?? null;
      record[field.name] = defaultValue;
      writes[field.name] = defaultValue;
    }
  }
  for (const field of fields) {
    if (field.type === "alias") continue;
    const effective = effectiveFields.get(field.name)!;
    const value = record[field.name];
    if (
      !effective.readonly &&
      !(effective.hidden && effective.clear_hidden_value_on_save) &&
      effective.required &&
      (value === null || value === undefined || value === "")
    ) {
      throw new EtHttpError(422, `Field '${field.label || field.name}' is required.`);
    }
    if (
      field.validation.conditions.length > 0 &&
      !field_rule_matches(field.validation, record)
    ) {
      throw new EtHttpError(
        422,
        field.validation_message ||
          `Field '${field.label || field.name}' does not meet its validation rules.`
      );
    }
  }
}

function assert_hidden_clear_is_writable(
  field: Pick<
    CmsField,
    | "name"
    | "label"
    | "required"
    | "options"
    | "hidden"
    | "clear_hidden_value_on_save"
    | "conditions"
  >
): void {
  const defaultValue = field.options.default;
  if (
    field.required &&
    (defaultValue === null || defaultValue === undefined || defaultValue === "") &&
    (field.hidden && field.clear_hidden_value_on_save) ||
      field.conditions.some(
        (condition) =>
          condition.hidden === true && condition.clear_hidden_value_on_save === true
      )
  ) {
    throw new EtHttpError(
      400,
      `Field '${field.label || field.name}' cannot clear a hidden value while required without a default value.`
    );
  }
}

function coerce_value(field: CmsField, raw: unknown): unknown {
  switch (field.type) {
    case "integer":
    case "relation": {
      const parsed = Number(raw);
      if (!Number.isFinite(parsed)) {
        throw new EtHttpError(422, `Field '${field.label || field.name}' must be an integer.`);
      }
      return Math.trunc(parsed);
    }
    case "decimal": {
      const parsed = Number(raw);
      if (!Number.isFinite(parsed)) {
        throw new EtHttpError(422, `Field '${field.label || field.name}' must be a number.`);
      }
      return parsed;
    }
    case "boolean":
      return bool(raw) ? 1 : 0;
    case "json":
      return typeof raw === "string" ? raw : JSON.stringify(raw);
    case "datetime":
      return typeof raw === "string" ? raw : new Date(String(raw)).toISOString();
    default:
      return String(raw);
  }
}

function sanitize_row(row: Row): Record<string, unknown> {
  const result: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(row)) {
    if (typeof value === "bigint") result[key] = value.toString();
    else if (Buffer.isBuffer(value)) result[key] = `0x${value.toString("hex")}`;
    else result[key] = value ?? null;
  }
  return result;
}

export function format_record_for_api(
  row: Record<string, unknown>,
  fields: CmsField[]
): Record<string, unknown> {
  const byName = new Map(fields.map((field) => [field.name, field]));
  const result: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(row)) {
    const field = byName.get(key);
    if (!field) {
      result[key] = value;
      continue;
    }
    if (field.type === "json" && typeof value === "string" && value !== "") {
      try {
        result[key] = JSON.parse(value) as unknown;
        continue;
      } catch {
        // Keep malformed JSON visible instead of hiding it.
      }
    }
    result[key] = field.type === "boolean" ? bool(value) : value;
  }
  return result;
}

export async function collection_fields(
  collectionName: string
): Promise<CmsField[]> {
  return (await require_collection(collectionName)).fields;
}

export async function collection_exists(name: string): Promise<boolean> {
  await ensure_cms_schema();
  return (await collection_row(name)) !== undefined;
}

export async function create_starter_collection(): Promise<CmsCollectionWithFields> {
  if (await collection_exists("posts")) {
    return await get_collection("posts");
  }
  return await create_collection({
    name: "posts",
    label: "Posts",
    icon: "file-text",
    note: "A starter collection for articles, notes or announcements.",
    fields: [
      { name: "title", label: "Title", type: "string", required: true },
      { name: "slug", label: "Slug", type: "string", unique: true },
      { name: "excerpt", label: "Excerpt", type: "text" },
      { name: "body", label: "Body", type: "text" },
      {
        name: "status",
        label: "Status",
        type: "select",
        options: {
          choices: [
            { text: "Draft", value: "draft" },
            { text: "Published", value: "published" },
            { text: "Archived", value: "archived" },
          ],
          default: "draft",
        },
      },
      { name: "published_at", label: "Published At", type: "datetime" },
      { name: "cover_image", label: "Cover Image", type: "image" },
      { name: "featured", label: "Featured", type: "boolean" },
    ],
  });
}

